// Command gen regenerates site/docs from the canonical docs/ tree.
//
// site/docs used to be a hand-copied duplicate of docs/ with lowercased
// filenames. Two problems came with that: the copies silently rot the moment
// docs/ is edited, and every link that pointed outside docs/ (../HARDENING.md,
// ../web/docs/routing.md, ../llmux.example.json) was dead inside the site
// bundle, which ships only the docs it lists.
//
// So docs/ is now the single source and site/docs is generated: same bytes,
// filenames lowercased to match site/docs.html, and every relative link either
// re-pointed at its sibling in the bundle or rewritten to an absolute repo URL.
// TestSiteDocsInSync fails if the two ever diverge, so the site cannot ship
// stale docs.
//
// Usage:
//
//	go run ./site/gen      # rewrite site/docs
//	go test ./site/gen     # verify site/docs is current (runs in CI)
package main

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"
)

// repoURL is where links that cannot resolve inside the site bundle are sent.
const repoURL = "https://github.com/vul-os/llmux/blob/main/"

// banner marks the output as generated. It is an HTML comment, so it renders as
// nothing in the site's markdown viewer.
const banner = "<!-- Generated from %s by `go run ./site/gen`. Do not edit this file. -->\n"

// page is one generated site doc: a repo-relative source and the filename it
// takes inside site/docs (which must match the nav list in site/docs.html).
type page struct {
	src string
	dst string
}

// pages is the docs the site bundle ships, in nav order.
var pages = []page{
	{"docs/GETTING-STARTED.md", "getting-started.md"},
	{"docs/client-examples.md", "client-examples.md"},
	{"docs/architecture.md", "architecture.md"},
	{"docs/configuration.md", "configuration.md"},
	{"docs/api.md", "api.md"},
	{"docs/LLM-ACCESS.md", "llm-access.md"},
	{"docs/control-plane.md", "control-plane.md"},
	{"docs/ADMIN-GUIDE.md", "admin-guide.md"},
	{"docs/operations.md", "operations.md"},
	{"docs/TROUBLESHOOTING.md", "troubleshooting.md"},
	{"ROADMAP.md", "roadmap.md"},
	{"docs/parity.md", "parity.md"},
	{"CHANGELOG.md", "changelog.md"},
}

// linkRE matches a markdown link/image target.
var linkRE = regexp.MustCompile(`\]\(([^)\s]+)\)`)

// screenshotsPrefix is the docs/ subtree that ships alongside site/docs as a
// sibling directory (site/screenshots), rather than through this generator.
const screenshotsPrefix = "docs/screenshots/"

// rewriteLinks re-points every relative link in a doc so it resolves inside the
// site bundle. A link to another generated page becomes that page's site
// filename; a link into docs/screenshots/ becomes a "../screenshots/…" link,
// which site/docs.html's own loader further normalizes at render time to
// "./screenshots/…" (relative to site/docs.html, where site/screenshots
// lives) — this form also resolves for TestSiteDocsHaveNoBrokenLinks, since
// path.Join("site/docs", "../screenshots/x.png") cleans straight to the real
// file. Anything else (repo-root files, web/docs/, source paths) becomes an
// absolute URL into the repository. Absolute URLs and bare fragments pass
// through untouched.
func rewriteLinks(srcPath, body string) string {
	srcDir := path.Dir(filepath.ToSlash(srcPath))
	if srcDir == "." {
		srcDir = ""
	}
	byPath := map[string]string{}
	for _, p := range pages {
		byPath[p.src] = p.dst
	}
	return linkRE.ReplaceAllStringFunc(body, func(m string) string {
		target := linkRE.FindStringSubmatch(m)[1]
		if strings.HasPrefix(target, "http://") || strings.HasPrefix(target, "https://") ||
			strings.HasPrefix(target, "mailto:") || strings.HasPrefix(target, "#") {
			return m
		}
		file, frag := target, ""
		if i := strings.IndexByte(target, '#'); i != -1 {
			file, frag = target[:i], target[i:]
		}
		if file == "" { // pure fragment
			return m
		}
		rel := path.Clean(path.Join(srcDir, file))
		if dst, ok := byPath[rel]; ok {
			return "](" + dst + frag + ")"
		}
		if strings.HasPrefix(rel, screenshotsPrefix) {
			return "](../screenshots/" + strings.TrimPrefix(rel, screenshotsPrefix) + frag + ")"
		}
		return "](" + repoURL + rel + frag + ")"
	})
}

// render produces the generated bytes for one page.
func render(srcPath, body string) string {
	return fmt.Sprintf(banner, filepath.ToSlash(srcPath)) + rewriteLinks(srcPath, body)
}

// generate reads every source page under root and returns dst filename ->
// generated content.
func generate(root string) (map[string]string, error) {
	out := make(map[string]string, len(pages))
	for _, p := range pages {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p.src)))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", p.src, err)
		}
		out[p.dst] = render(p.src, string(body))
	}
	return out, nil
}

// findRoot walks up from dir to the module root.
func findRoot(dir string) (string, error) {
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory")
		}
		dir = parent
	}
}

func main() {
	cwd, err := os.Getwd()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	root, err := findRoot(cwd)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	files, err := generate(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	dir := filepath.Join(root, "site", "docs")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gen:", err)
			os.Exit(1)
		}
	}
	fmt.Printf("gen: wrote %d docs to site/docs\n", len(files))
}
